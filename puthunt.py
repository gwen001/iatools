class Http:
    def __init__(self, console, timeout=20.0, delay=0.0, proxy=None,
                 extra_headers=None, retries=2, body_cap=200000,
                 env_proxy=True):
        self.con = console
        # a single float applies the same budget to the handshake and to the
        # response; a slow old appliance needs a long read and a short connect
        self.timeout = (min(10.0, timeout), timeout)
        self.retries = max(0, retries)
        self.body_cap = body_cap
        self.proxy = proxy
        self.env_proxy = env_proxy
        self.base_headers = {
            "User-Agent": UA,
            # no compression: a gzipped read-back costs CPU and buys nothing
            "Accept-Encoding": "identity",
            "Accept": "*/*",
        }
        # kept separately: the operator's explicit -H / -r headers (Cookie,
        # Authorization, custom routing). They go into every generated curl,
        # because a PoC for an authenticated path that omits the session is
        # not a PoC.
        self.operator_headers: dict = {}
        for h in extra_headers or []:
            if ":" in h:
                k, _, v = h.partition(":")
                self.base_headers[k.strip()] = v.strip()
                self.operator_headers[k.strip()] = v.strip()
        self._min_gap = max(0.0, delay)
        self._next = 0.0
        self._rate_lk = threading.Lock()
        self._cnt_lk = threading.Lock()
        self._local = threading.local()
        self.count = 0
        self.retried = 0
        self.err_classes: dict[str, int] = {}

    # ---- sessions

    def _new_session(self) -> requests.Session:
        s = requests.Session()
        retry = build_retry()
        s.mount("https://", LegacyTLSAdapter(max_retries=retry,
                                             pool_connections=8, pool_maxsize=8))
        s.mount("http://", HTTPAdapter(max_retries=retry,
                                       pool_connections=8, pool_maxsize=8))
        # belt and braces: verify is also passed on every send()
        s.verify = False
        s.trust_env = self.env_proxy
        return s

    def _session(self) -> requests.Session:
        s = getattr(self._local, "s", None)
        if s is None:
            s = self._new_session()
            self._local.s = s
        return s

    def _drop_session(self):
        """
        Throw the thread's connection pool away.

        This is the fix for the commonest transport failure: a keep-alive socket
        the peer closed between two probes. Servers very often close after
        refusing a PUT with 405/403 and do not send Connection: close, so the
        next probe writes into a dead TLS session and OpenSSL reports a syscall
        error -- "[SYS] unknown error (_ssl.c:NNNN)". A fresh pool guarantees
        the retry is a fresh TCP+TLS connection.
        """
        s = getattr(self._local, "s", None)
        if s is not None:
            try:
                s.close()
            except Exception:
                pass
        self._local.s = None

    # ---- rate limiting

    def _throttle(self):
        if self._min_gap <= 0:
            return
        with self._rate_lk:
            now = time.monotonic()
            wait = max(0.0, self._next - now)
            self._next = max(now, self._next) + self._min_gap
        while wait > 0 and not _STOP.is_set():
            chunk = min(0.25, wait)
            time.sleep(chunk)
            wait -= chunk

    def _note(self, cls: str):
        with self._cnt_lk:
            self.err_classes[cls] = self.err_classes.get(cls, 0) + 1

    # ---- the request

    def _once(self, method, url, data, headers, allow_redirects) -> Resp:
        h = dict(self.base_headers)
        if headers:
            h.update(headers)
        try:
            # The literal path must survive: requests normalises dot segments
            # and duplicate slashes while preparing, which would destroy the
            # ".jsp/" and "%20" evasion spellings. So prepare against the
            # host root and then substitute the real target.
            base = urlsplit(url)
            safe = urlunsplit((base.scheme, base.netloc, "/", "", ""))
            req = requests.Request(method, safe, data=data, headers=h).prepare()
            req.url = wire_safe(url)
            req.method = method        # prepare() upper-cases; keep "put" as-is
            kw = dict(timeout=self.timeout, verify=False,
                      allow_redirects=allow_redirects, stream=True)
            if self.proxy:
                kw["proxies"] = {"http": self.proxy, "https": self.proxy}
            elif not self.env_proxy:
                kw["proxies"] = {}
            r = self._session().send(req, **kw)
            try:
                buf = bytearray()
                for chunk in r.iter_content(16384):
                    buf += chunk
                    if len(buf) >= self.body_cap:
                        break
                body = bytes(buf[:self.body_cap]).decode("utf-8", "replace")
            finally:
                r.close()
            return Resp(r.status_code, body, dict(r.headers))
        except Exception as e:
            # not just RequestException: a malformed evasion target can raise
            # UnicodeError/ValueError out of the url layer, and losing a whole
            # host to that would be worse than recording it
            msg = f"{type(e).__name__}: {e}"
            return Resp(0, "", {}, error=msg, err_class=classify_error(msg))

    def req(self, method, url, data=None, headers=None, allow_redirects=False,
            retries=None) -> Resp:
        if _STOP.is_set():
            return Resp(0, "", {}, error="aborted by operator",
                        err_class="aborted")
        attempts = (self.retries if retries is None else retries) + 1
        last = None
        for i in range(attempts):
            self._throttle()
            if _STOP.is_set():
                return Resp(0, "", {}, error="aborted by operator",
                            err_class="aborted")
            with self._cnt_lk:
                self.count += 1
            r = self._once(method, url, data, headers, allow_redirects)
            if r.ok:
                r.attempts = i + 1
                return r
            last = r
            if r.err_class not in _RETRYABLE or i + 1 >= attempts:
                break
            # a dead pool entry is the likeliest cause, so start from scratch
            self._drop_session()
            with self._cnt_lk:
                self.retried += 1
            self.con.debug(f"retry {i+1}/{attempts-1} {method} {url} "
                           f"[{r.err_class}] {r.error[:80]}")
            time.sleep(min(2.0, 0.4 * (2 ** i)))
        self._note(last.err_class or "other")
        last.attempts = attempts
        return last


