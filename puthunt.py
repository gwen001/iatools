def status_key(code):
    try:
        code = int(code)
    except (TypeError, ValueError):
        return "dim"
    if 200 <= code < 300:
        return "ok"
    if code == 403:
        return "warn"          # handler present, denied -- the interesting one
    if code in (401, 405):
        return "bad"
    if 300 <= code < 400:
        return "dim"
    return "dim"


