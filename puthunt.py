def load_urls(path):
    out = []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                out.append(line if line.startswith(("http://", "https://"))
                           else "https://" + line)
    return out


# ----------------------------------------------------------------------------
# raw HTTP request (-r)
# ----------------------------------------------------------------------------

# Headers from the request file that must not be replayed verbatim: requests
# derives them (Host from the URL, Content-Length from the body) or they would
# interfere with the write tests (Accept-Encoding -> a compressed read-back).
_RAW_SKIP_HEADERS = frozenset({
    "host", "content-length", "connection", "proxy-connection", "keep-alive",
    "accept-encoding", "transfer-encoding", "te", "expect",
})


@dataclass
class RequestSpec:
    method: str
    url: str
    headers: dict          # replayed on every request (Cookie, auth, ...)


def _infer_scheme(headers: dict) -> str:
    """http by default; https if an Origin/Referer is itself https."""
    for h in ("Origin", "Referer"):
        v = headers.get(h) or headers.get(h.lower())
        if v and v.lower().startswith("https://"):
            return "https"
        if v and v.lower().startswith("http://"):
            return "http"
    return "http"


def parse_raw_request(path: str, force_ssl: bool = False) -> RequestSpec:
    """
    Parse a raw HTTP request file (Burp/ZAP export) into a RequestSpec: method,
    absolute URL and headers to replay. puthunt drives its own PUT/WebDAV probes
    against the URL's host and path, so only the target and the auth headers are
    taken from the capture; the request body is ignored. The scheme is http by
    default (inferred from Origin/Referer, or forced with --force-ssl) since an
    origin-form request line does not carry one.
    """
    with open(path, "rb") as fh:
        text = fh.read().decode("utf-8", errors="replace").replace("\r\n", "\n")

    head = text.split("\n\n", 1)[0]
    lines = head.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    if not lines:
        raise ValueError("empty request file")

    parts = lines[0].strip().split()
    if len(parts) < 2:
        raise ValueError(f"invalid request line: {lines[0]!r}")
    method, target = parts[0].upper(), parts[1]

    headers: dict = {}
    for ln in lines[1:]:
        if ":" in ln:
            k, _, v = ln.partition(":")
            if k.strip():
                headers[k.strip()] = v.strip()

    host = headers.get("Host") or headers.get("host")
    if target.startswith(("http://", "https://")):
        url = target
        if force_ssl and url.startswith("http://"):
            url = "https://" + url[len("http://"):]
    else:
        if not host:
            raise ValueError("no Host header and non-absolute URI: "
                             "cannot build the URL")
        scheme = "https" if force_ssl else _infer_scheme(headers)
        if not target.startswith("/"):
            target = "/" + target
        url = f"{scheme}://{host}{target}"

    fwd = {k: v for k, v in headers.items() if k.lower() not in _RAW_SKIP_HEADERS}
    return RequestSpec(method, url, fwd)


def main(argv=None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if not args.url and not args.list and not args.request:
        parser.print_help()
        return 2
    set_color(not (args.no_color or os.environ.get("NO_COLOR")))

    # -r takes precedence: target + auth headers come from a captured request
    spec = None
    if args.request:
        if not os.path.isfile(args.request):
            print(f"error: no such file: {args.request}", file=sys.stderr)
            return 2
        try:
            spec = parse_raw_request(args.request, force_ssl=args.force_ssl)
        except Exception as e:
            print(f"error: cannot parse request ({args.request}): {e}",
                  file=sys.stderr)
            return 2
        if args.url or args.list:
            print("note: -r takes precedence; -u/-l ignored", file=sys.stderr)
        urls = [spec.url]
        # request headers first, -H after (so -H can override)
        args.header = [f"{k}: {v}" for k, v in spec.headers.items()] + list(args.header)
    else:
        urls = []
        if args.url:
            urls.append(args.url if args.url.startswith(("http://", "https://"))
                        else "https://" + args.url)
        if args.list:
            if not os.path.isfile(args.list):
                print(f"error: no such file: {args.list}", file=sys.stderr)
                return 2
            urls.extend(load_urls(args.list))
        urls = list(dict.fromkeys(urls))
    if not urls:
        print("error: no targets", file=sys.stderr)
        return 2

    if args.path_threads is None:
        # one target means the candidate paths are the only parallelism
        # available, and a list already parallelises across hosts
        args.path_threads = 4 if len(urls) == 1 else 1

    con = Console(args.verbosity)
    status = Status(con, len(urls), interval=args.status_interval,
                    enabled=len(urls) > 1)

    print(paint(BANNER, "head"))
    print(f"  targets {paint(str(len(urls)), 'b')}   threads {args.threads}"
          f"   paths/target {args.path_threads}   timeout {args.timeout:.0f}s"
          f"   retries {args.retries}")
    print(f"  mode    "
          + paint("WRITE (dated file + run token, no other content)", "bad")
          + "      extensions "
          + (paint("markup + executables + evasion + MOVE", "bad")
             if args.executables
             else paint("one .txt per writable path", "ok")))
    print("  tls     " + paint("verification DISABLED", "warn")
          + " (CERT_NONE, no hostname check, TLS1.0+, SECLEVEL=0, "
            "legacy renegotiation allowed)")
    extra = parse_paths(args.paths)
    if extra:
        src = "file" if args.paths and os.path.isfile(args.paths) else "list"
        print(f"  paths   {len(extra)} extra from --paths ({src})"
              + ("  + built-in wordlist" if args.all_dirs else ""))
    elif args.all_dirs:
        print(f"  paths   built-in wordlist ({len(FULL_DIRS)} entries)")
    if args.proxy:
        print(f"  proxy   {args.proxy}")
    print()

    http = Http(con, timeout=args.timeout, delay=args.delay, proxy=args.proxy,
                extra_headers=args.header, retries=args.retries,
                env_proxy=args.env_proxy)
    hunter = PutHunter(http, con, args, status)

    started = time.time()
    status.start()

    def one(u):
        try:
            hunter.run_target(u)
        except Exception as e:
            con.error(f"{u}: {type(e).__name__}: {e}")
        finally:
            status.host_done()

    try:
        if args.threads > 1 and len(urls) > 1:
            with concurrent.futures.ThreadPoolExecutor(
                    max_workers=args.threads) as pool:
                list(pool.map(one, urls))
        else:
            for u in urls:
                one(u)
    except KeyboardInterrupt:
        _STOP.set()
        con.error("interrupted by user — finishing cleanup")
    finally:
        status.stop()
        if status.enabled:
            status.emit(label="final")

    elapsed = time.time() - started
    real = [f for f in hunter.findings if f.sev != INFO]
    print(f"\n  {paint(str(len(real)), 'b')} finding(s) from {http.count} "
          f"requests in {elapsed:.0f}s"
          + (f"  ({http.retried} retried)" if http.retried else ""))
    for sev in (CRIT, HIGH, MED, LOW):
        n = sum(1 for f in hunter.findings if f.sev == sev)
        if n:
            print(f"    {paint(sev, sev):<20} {n}")
    if hunter.deduped:
        print(f"  {paint('deduplicated', 'ok')}: {hunter.deduped} repeated "
              f"host+path pair(s) not retested")

    # Transport failures by class. This is the part that tells you whether a
    # quiet run means "nothing writable" or "half the scope never answered".
    if http.err_classes:
        print(f"\n  {paint('--- transport failures by class ---', 'b')}")
        for cls, n in sorted(http.err_classes.items(), key=lambda kv: -kv[1]):
            print(f"    {paint(f'{cls:<11}', 'warn')} {n:>5}   "
                  f"{paint(ERR_HINTS.get(cls, ''), 'dim')}")
    if hunter.skipped:
        print(f"  {paint('skipped targets', 'warn')}: {len(hunter.skipped)}")
        for s in hunter.skipped[:10]:
            print(f"    - {s['url']}  [{s['reason']}]")
        if len(hunter.skipped) > 10:
            print(f"    ... and {len(hunter.skipped) - 10} more")

    # 2xx PUTs that stored nothing. Reported as context, never as a finding:
    # a CDN or reverse proxy answering a write it discards is the normal case
    # here, and it explains why a run made requests and found nothing.
    if hunter.unstored:
        print(f"  {paint('2xx PUT with nothing stored', 'warn')}: "
              f"{hunter.unstored} — the write was accepted and discarded "
              f"(proxy/CDN or catch-all path), not a write")

    # Everything this run actually put on the target, and whether it is still
    # there. Printed unconditionally: the operator has to be able to tell the
    # client. Entries that were never read back AND are verified absent are
    # left out -- listing a file the tool itself concluded was never created
    # is how a clean run comes to look like it left something behind.
    real_art = [a for a in hunter.artifacts
                if a["confirmed"] or a["removed"] is not True]
    if real_art:
        gone = [a for a in real_art if a["removed"] is True]
        left = [a for a in real_art if a["removed"] is False]
        unk = [a for a in real_art if a["removed"] is None]
        print(f"\n  {paint('--- artefacts created on the target ---', 'b')}")
        print(f"    created: {len(real_art)}    "
              f"removed: {len(gone)}    "
              f"remaining: {paint(str(len(left)), 'bad' if left else 'ok')}    "
              f"unknown: {paint(str(len(unk)), 'warn' if unk else 'ok')}")
        for a in real_art:
            state = (paint("removed", "ok") if a["removed"] is True
                     else paint("REMAINS", "bad") if a["removed"] is False
                     else paint("UNKNOWN", "warn"))
            note = "" if a["confirmed"] else "  (never read back — unproven)"
            print(f"    {state}  [{a['kind']}] {a['url']}{note}")
        if left or unk:
            print(paint("    Disclose the url(s) above so the client can delete "
                        "them.", "bad"))
    return 1 if real else 0


if __name__ == "__main__":
    sys.exit(main())
