# Characters that cannot travel in a request target. '%' is deliberately NOT
# encoded: the "%20" evasion spelling has to reach the wire intact.
_WIRE_BAD = set(' "<>\\^`{|}\x7f') | {chr(c) for c in range(0x21)}


def wire_safe(url: str) -> str:
    out = []
    for ch in url:
        if ch in _WIRE_BAD or ord(ch) > 0x7e:
            out.extend(f"%{b:02X}" for b in ch.encode("utf-8"))
        else:
            out.append(ch)
    return "".join(out)


def join_url(base: str, path: str = "", name: str = "") -> str:
    """
    Concatenate without normalising.

    The previous build did this with .replace("//", "/").replace(":/", "://"),
    which also collapsed legitimate double slashes inside a path and would
    rewrite any "//" an evasion spelling introduced. Plain concatenation of
    already-normalised pieces is both shorter and correct.
    """
    b = base.rstrip("/")
    p = path or ""
    if p and not p.startswith("/"):
        p = "/" + p
    p = p.rstrip("/")
    u = b + p
    if name:
        u += "/" + name.lstrip("/")
    return u


def dir_url(base: str, path: str = "") -> str:
    u = join_url(base, path)
    return u if u.endswith("/") else u + "/"


def other_scheme(base: str) -> str:
    u = urlsplit(base)
    alt = "http" if u.scheme == "https" else "https"
    # drop a default port so http://host:443 does not become the fallback
    netloc = u.netloc
    if u.scheme == "https" and netloc.endswith(":443"):
        netloc = netloc[:-4]
    elif u.scheme == "http" and netloc.endswith(":80"):
        netloc = netloc[:-3]
    return f"{alt}://{netloc}"


def poc_pattern(token: str) -> re.Pattern:
    """
    The exact shape written to the target: yyyy-mm-dd <token>.

    Confirmation is a GET followed by this regex, and nothing else counts. A
    status code cannot confirm a write -- a catch-all vhost answers 2xx to
    every name, a CDN answers 2xx for writes the origin discarded -- and a bare
    substring search can be satisfied by a page that merely quotes the name. A
    match here means the server handed back the file this run created.
    """
    return re.compile(r"\d{4}-\d{2}-\d{2}\s+" + re.escape(token))


def parse_paths(value) -> list[str]:
    """
    --paths takes either a comma-separated list or a file of paths, because
    which one is convenient depends on whether you have three or three hundred.
    A file may also hold comma-separated entries, and # comments.
    """
    if not value:
        return []
    if isinstance(value, (list, tuple)):
        raw = list(value)
    elif os.path.isfile(value):
        with open(value, encoding="utf-8", errors="replace") as fh:
            raw = fh.read().splitlines()
    else:
        raw = [value]
    out = []
    for line in raw:
        for chunk in line.split("#", 1)[0].split(","):
            chunk = chunk.strip().strip("/")
            if chunk:
                out.append("/" + chunk)
    return list(dict.fromkeys(out))


