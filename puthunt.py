#!/usr/bin/env python3
r"""
puthunt — server-level HTTP PUT / WebDAV write testing.

Three phases:
  1. DETECT     map where a write handler is attached, by path
  2. EXPLOIT    prove the write, then establish whether it reaches an
                executable extension (the line between High and Critical)
  3. COLLECT    account for every artefact created, and remove it

Write permission is a property of a PATH, not of a server. Config is
block-scoped (Apache <Location>, nginx location{}, IIS virtual directories,
Tomcat per-servlet readonly), filesystem permissions differ per directory, and
/assets/ frequently routes to an entirely different backend than /. A tool that
probes only "/" reports secure on hosts that are wide open one directory down,
so this enumerates candidate paths and maps the boundary.

Reading the codes matters more than counting them:
    405  no write handler at this scope        -> move on
    403  handler IS here, something denied it  -> keep pushing
    409  parent collection missing             -> MKCOL, then retry the PUT
    2xx  wrote something                       -> verify by GET before believing

A 2xx on PUT is never treated as proof. Proxies, CDNs and load balancers return
200/201 for writes the origin discards, and a catch-all vhost answers 2xx for
every name there is, so an apparent success is confirmed one way only: fetch
the file back and match its body against the exact shape that was written.

    body written:   yyyy-mm-dd <random token>
    confirmation:   GET, then /\d{4}-\d{2}-\d{2}\s+<token>/

A finding carries CONFIRMED when, and only when, that regex matched. Nothing
else earns it -- not a 201, not an Allow header, not a DAV header. Before the
first write, one GET for a name that cannot exist calibrates the path, so a
host that answers 2xx to everything is recognised as such instead of being
reported.

The file written contains the date and a random token, and nothing else. Its
name and body are generated by the tool; there is no option to upload arbitrary
content, and no webshell is ever written -- an inert dated file proves the same
control failure.

TRANSPORT
    TLS verification is disabled by construction, in four places at once:
    CERT_NONE, hostname checking off, verify=False on the session and on every
    send(). The context is also deliberately permissive (TLS 1.0+, SECLEVEL=0,
    legacy renegotiation allowed) because urllib3 2.x refuses TLS < 1.2 and
    weak DH/ciphers by default, and half the hosts worth testing for WebDAV are
    old appliances that speak nothing else.

    Transport failures are retried on a fresh connection, classified, and
    reported per class at the end of the run. A host is skipped only after
    every scheme and every retry has failed -- a single dropped socket no
    longer loses a target.

For authorized testing only.
"""

