@dataclass
class Finding:
    title: str
    url: str
    method: str
    sev: str = HIGH
    evidence: str = ""
    curl: str = ""
    # CONFIRMED means: the artefact was fetched back and its body matched
    # /yyyy-mm-dd <token>/. Anything without it rests on a status code or a
    # header, which is weaker and is labelled as such.
    confirmed: bool = False
    proof: str = ""
    # A complete, literal, copy-pasteable reproduction. Every URL, body and
    # header is the real one this run used, so the client replays the finding
    # without reconstructing anything -- and the sequence ends by removing
    # whatever it created. Lines starting with # are comments.
    repro: list = field(default_factory=list)
    when: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


@dataclass
class Resp:
    status: int
    body: str
    headers: dict = field(default_factory=dict)
    error: str = ""
    err_class: str = ""
    attempts: int = 1

    @property
    def ok(self):
        """The request completed. Says nothing about the status code."""
        return not self.error

    def header(self, name, default=""):
        for k, v in self.headers.items():
            if k.lower() == name.lower():
                return v
        return default


@dataclass
class Baseline:
    """
    What a path does with a filename that was never written.

    This is the calibration step the tool was missing, and its absence was the
    source of every remaining false positive. A host that answers 2xx to any
    URL -- a catch-all vhost, a SPA fallback, a parking page, an edge rule,
    "<html>empty</html>" on every verb and every path -- makes every
    bare-status check meaningless: the PUT is "accepted", the file is "still
    served" after the DELETE, and nothing was ever written. One GET for a
    random name that cannot exist settles it before any conclusion is drawn.
    """
    status: int = 0
    body: str = ""
    err_class: str = ""

    @property
    def catch_all(self) -> bool:
        """A name that was never written is served with a 2xx."""
        return 200 <= self.status < 300

    @property
    def distinguishes(self) -> bool:
        """The server says "not found" when a thing is not found."""
        return self.status in (404, 410)


@dataclass
class WriteResult:
    ok: bool = False
    status: int = 0
    url: str = ""
    err_class: str = ""
    how: str = "PUT"
    token: str = ""
    body: str = ""
    bl: Baseline | None = None


