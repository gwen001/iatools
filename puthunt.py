def build_ssl_context() -> ssl.SSLContext:
    """
    A deliberately permissive client context.

    Verification off is only half of it. urllib3 2.x defaults to TLS 1.2 and
    OpenSSL 3 defaults to SECLEVEL=2, which between them refuse to talk to the
    class of host most likely to have WebDAV mounted: old Tomcat, iLO/iDRAC,
    printers, appliances, anything with a 1024-bit DH parameter. Those refusals
    surface as SSLError and get read as "the target is down" when the target is
    merely old.
    """
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")        # TLSv1 is a DeprecationWarning
        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        # order matters: check_hostname must go off before CERT_NONE is set
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        try:
            ctx.minimum_version = ssl.TLSVersion.TLSv1
        except (AttributeError, ValueError):
            pass
        for opt in ("OP_LEGACY_SERVER_CONNECT",      # RFC 5746 not implemented
                    "OP_IGNORE_UNEXPECTED_EOF",      # truncated close
                    "OP_ALLOW_UNSAFE_LEGACY_RENEGOTIATION"):
            ctx.options |= getattr(ssl, opt, 0)
        for spec in ("ALL:@SECLEVEL=0", "DEFAULT:@SECLEVEL=0", "ALL", "DEFAULT"):
            try:
                ctx.set_ciphers(spec)
                break
            except ssl.SSLError:
                continue
        try:
            # offer http/1.1 like a browser; some middleboxes behave oddly when
            # no ALPN is offered at all
            ctx.set_alpn_protocols(["http/1.1"])
        except (AttributeError, NotImplementedError):
            pass
    return ctx


_SSL_CTX = build_ssl_context()


class LegacyTLSAdapter(HTTPAdapter):
    """Mounts the permissive context on both direct and proxied pools."""

    def init_poolmanager(self, *a, **kw):
        kw["ssl_context"] = _SSL_CTX
        return super().init_poolmanager(*a, **kw)

    def proxy_manager_for(self, *a, **kw):
        kw["ssl_context"] = _SSL_CTX
        return super().proxy_manager_for(*a, **kw)


def build_retry():
    """
    One transparent retry at connect time only.

    read=0 on purpose: a read or protocol failure on a pooled connection is
    handled a level up, by retrying on a brand-new session, which is both more
    reliable and visible in -v 2. Letting urllib3 retry reads as well doubles
    the cost of every timing-out host for no extra coverage. HTTP status codes
    are never retried (status=0) -- a 403 is a result, not a failure.
    """
    kw = dict(total=1, connect=1, read=0, status=0, redirect=0,
              backoff_factor=0.3, raise_on_status=False,
              respect_retry_after_header=False)
    for extra in ({"other": 1, "allowed_methods": None},
                  {"allowed_methods": None},
                  {"method_whitelist": False},
                  {}):
        try:
            return urllib3.util.Retry(**kw, **extra)
        except TypeError:
            continue
    return 1


