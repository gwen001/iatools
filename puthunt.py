def classify_error(text: str) -> str:
    t = (text or "").lower()
    if not t:
        return "other"
    if "aborted by operator" in t:
        return "aborted"
    for name, needles in _ERR_RULES:
        for n in needles:
            if n in t:
                return name
    return "other"


