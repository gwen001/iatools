class PutHunter:
    POC_PREFIX = "puthunt-poc-"

    def __init__(self, http: Http, con: Console, args, status: Status = None):
        self.http = http
        self.con = con
        self.args = args
        self.status = status
        self.findings: list[Finding] = []
        self.skipped: list[dict] = []
        # every file and collection this run created; anything not removed
        # must be disclosed
        self.artifacts: list[dict] = []
        self.extra_paths = parse_paths(getattr(args, "paths", None))
        # (base, path) pairs already exercised. A list of URLs on one host, or
        # URLs sharing ancestors, otherwise re-tests the same directory many
        # times over: same request, same write, same answer.
        self._seen: set[tuple[str, str]] = set()
        self.deduped = 0
        # PUTs answered 2xx whose result could not be read back: a proxy or CDN
        # accepting and discarding the write, a catch-all path, or a write-only
        # directory. Counted so a quiet run is explainable, never reported as a
        # finding and never counted as an artefact unless it is actually there.
        self.unstored = 0
        self._lk = threading.Lock()

    # ---- bookkeeping

    def _claim(self, base: str, path: str) -> bool:
        """True the first time a (host, path) pair is seen, False afterwards."""
        u = urlsplit(base)
        key = (f"{u.scheme.lower()}://{u.netloc.lower()}", "/" + path.strip("/"))
        with self._lk:
            if key in self._seen:
                self.deduped += 1
                return False
            self._seen.add(key)
            return True

    def add(self, f: Finding):
        with self._lk:
            self.findings.append(f)
        if self.status:
            self.status.record(f.sev)
        self.con.finding(f)

    def _ledger(self, url: str, kind: str, confirmed=True):
        """
        confirmed=False means the server returned 2xx to the PUT but the file
        was never read back. That is an artefact to account for, not an
        artefact known to exist, and nothing about it may be reported as a
        finding -- on a catch-all host every PUT looks like that.
        """
        with self._lk:
            self.artifacts.append({"url": url, "kind": kind, "removed": None,
                                   "confirmed": confirmed})

    def _mark(self, url: str, removed):
        with self._lk:
            for a in self.artifacts:
                if a["url"] == url:
                    a["removed"] = removed

    def _mark_confirmed(self, url: str):
        """Promote a ledger entry once the artefact has actually been seen."""
        with self._lk:
            for a in self.artifacts:
                if a["url"] == url:
                    a["confirmed"] = True

    # ---- the payload: datetime plus a token, and nothing else

    @staticmethod
    def _poc_parts() -> tuple[str, str]:
        """
        Returns (token, body). The body is exactly:

            yyyy-mm-dd <random token>

        The date is for whoever finds the file on the server afterwards. The
        token is what makes the read-back a proof: verification is a regex for
        that exact shape, so nothing but this run's own file can satisfy it --
        not a cached page, not a catch-all body, not a soft-404 that happens to
        print a date, not a concurrent write by this same tool.
        """
        token = secrets.token_hex(8)
        return token, f"{datetime.now(timezone.utc).strftime('%Y-%m-%d')} {token}"

    def _poc_name(self, token: str, ext="txt") -> str:
        # the token also goes in the name: int(time.time()) + pid handed two
        # threads writing into the same directory in the same second the same
        # filename, which corrupted both the read-back and the ledger
        return f"{self.POC_PREFIX}{token}.{ext}"

    # ---- reproduction

    _HEAD = "# paste the whole block — the first lines set the shared context"

    @staticmethod
    def _q(v) -> str:
        """
        Always single-quote. A report must never carry a bare URL: a '?', an
        '&' or a '$' in a path turns a pasted command into something else, and
        the evasion spellings are made of exactly those characters.
        """
        return "'" + str(v).replace("'", "'\\''") + "'"

    def repro_context(self) -> tuple[list, list]:
        """
        The preamble and the flags every command in a block shares.

        The User-Agent and the operator's own -H / -r headers are set once as
        shell variables rather than repeated on each of four long lines: the
        block stays readable in a report, it is still a single paste, and it is
        portable sh rather than bash arrays. A capture replayed from -r can
        carry a dozen headers, and inlining them would make the PoC unusable.
        """
        pre = [self._HEAD, f"UA={self._q(UA)}"]
        flags = ['-A "$UA"']
        for i, (k, v) in enumerate(self.http.operator_headers.items(), 1):
            pre.append(f"H{i}={self._q(f'{k}: {v}')}")
            flags.append(f'-H "$H{i}"')
        return pre, flags

    def _curl(self, method: str, url: str, data: str = None,
              headers: dict = None, show_headers=True, extra_flags=()) -> str:
        """
        One literal, shell-safe curl. No placeholders, ever: the client selects
        the line, pastes it, and sees what this run saw. The operator's session
        headers are replayed too, otherwise a finding on an authenticated path
        cannot be reproduced at all.
        """
        _, ctx = self.repro_context()
        parts = ["curl", "-sk"]
        if show_headers:
            parts.append("-i")
        if method != "GET":
            parts += ["-X", method]
        parts.extend(extra_flags)
        parts.append(self._q(url))
        parts.extend(ctx)
        for k, v in (headers or {}).items():
            parts += ["-H", self._q(f"{k}: {v}")]
        if data is not None:
            parts += ["--data-binary", self._q(data)]
        return " ".join(parts)

    def _repro(self, *lines) -> list:
        """Prefix a block with the shared context."""
        pre, _ = self.repro_context()
        out = list(pre)
        for ln in lines:
            out.extend(ln if isinstance(ln, list) else [ln])
        return out

    def _control_step(self, base: str, path: str, bl: Baseline = None) -> list:
        """
        The control request, as step 0.

        It is what makes the rest of the sequence defensible in a report: a
        name that was never written returns 404 here, so the 2xx on the write
        below is a write and not a catch-all answering every URL alike.
        """
        if bl is None or not bl.distinguishes:
            return []
        probe = join_url(base, path,
                         f"puthunt-control-{secrets.token_hex(4)}.txt")
        return [f"# 0. control: a name that was never written. Expect "
                f"{bl.status}. This is what proves the 2xx below is a write "
                f"and not a catch-all.",
                self._curl("GET", probe, show_headers=False,
                           extra_flags=("-o", "/dev/null", "-w",
                                        self._q(r"%{http_code}\n")))]

    def _repro_write(self, base: str, path: str, url: str, body: str,
                     method="PUT", headers=None, bl: Baseline = None,
                     confirm_at: str = None, pre: list = None,
                     post: list = None) -> list:
        """write -> confirm -> remove, with the real values throughout."""
        h = {"Content-Type": "text/plain"}
        h.update(headers or {})
        seen = confirm_at or url
        tail = [f"# 3. remove it, then re-run step 2: it must no longer return "
                f"the token.",
                self._curl("DELETE", seen)]
        if seen != url:
            tail.append(self._curl("DELETE", url))
        return self._repro(
            self._control_step(base, path, bl),
            list(pre or []),
            [f"# 1. write an inert file. The body is a date and a random "
             f"token: {body}",
             self._curl(method, url, data=body, headers=h)],
            list(post or []),
            [f"# 2. confirm the write. This must print exactly: {body}",
             self._curl("GET", seen, show_headers=False)],
            tail)

    # ---- phase 1: where is a write handler attached?

    def probe_options(self, base: str, path: str) -> Resp:
        r = self.http.req("OPTIONS", dir_url(base, path))
        if not r.ok:
            self.con.test(base, f"OPTIONS {path or '/'}", "err", r.err_class)
            return r
        allow = r.header("Allow") or r.header("Public")
        dav = r.header("DAV")
        self.con.test(base, f"OPTIONS {path or '/'}", r.status,
                      f"allow={allow or '-'}" + (f" DAV={dav}" if dav else ""))
        if dav:
            # LOW, not MEDIUM: a DAV header says a write-capable module is
            # mounted, which is where to look, not what is permitted. The
            # write test below is what carries a real severity.
            self.add(Finding(
                title="WebDAV advertised",
                url=dir_url(base, path), method="OPTIONS", sev=LOW,
                evidence=f"DAV: {dav}\nAllow: {allow or '-'}\n"
                         f"A DAV header means a write-capable module is mounted "
                         f"on this path. Not a write by itself.",
                repro=self._repro(
                    "# the DAV header is advertised on this path",
                    self._curl("OPTIONS", dir_url(base, path)))))
        return r

    # ---- phase 2: the write

    def _verify(self, url: str, token: str, follow=True) -> tuple[bool, Resp]:
        """One GET, then the regex. A hit is what CONFIRMED on a finding means."""
        v = self.http.req("GET", url, allow_redirects=follow)
        hit = bool(v.ok and v.status == 200 and poc_pattern(token).search(v.body))
        return hit, v

    @staticmethod
    def _proof(url: str, token: str) -> str:
        return (f"GET {url} returned 200 and the body matched "
                f"/\\d{{4}}-\\d{{2}}-\\d{{2}}\\s+{token}/ — the file this "
                f"run wrote, served back from the target.")

    def baseline(self, base: str, path: str) -> Baseline:
        """
        One GET for a name that cannot exist, before anything is written.

        Calibration, not a probe: it establishes whether this path's status
        codes mean anything at all. Everything downstream -- "was the write
        accepted", "is the artefact still there" -- is read against it.
        """
        probe = join_url(base, path,
                         f"puthunt-baseline-{secrets.token_hex(5)}.txt")
        r = self.http.req("GET", probe, allow_redirects=True)
        if not r.ok:
            self.con.test(base, f"baseline {(path or '').rstrip('/')}/<rand>",
                          "err", r.err_class)
            return Baseline(0, "", r.err_class)
        bl = Baseline(r.status, r.body[:4096])
        self.con.test(base, f"baseline {(path or '').rstrip('/')}/<rand>",
                      r.status,
                      "CATCH-ALL — 2xx for a name that does not exist"
                      if bl.catch_all else
                      ("statuses are meaningful here" if bl.distinguishes
                       else "ambiguous (neither 2xx nor 404)"))
        if bl.catch_all:
            self.con.warn(
                f"{dir_url(base, path)} answers {r.status} for filenames that "
                f"were never written: status codes carry no information on this "
                f"path, only the read-back token does")
        return bl

    def try_write(self, base: str, path: str, ext="txt", quiet=False,
                  name=None, verify_at=None, bl: Baseline = None) -> WriteResult:
        """
        One PUT, then a read-back.

        Only mutates when the server permits it: a 405/403/401 writes nothing,
        which is why detection and proof are the same request.

        verify_at lets an evasion spelling be read back under the name that
        matters after the server normalises it.
        """
        token, body = self._poc_parts()
        fname = name or self._poc_name(token, ext)
        url = join_url(base, path, fname)
        w = self.http.req("PUT", url, data=body.encode(),
                          headers={"Content-Type": "text/plain"})
        label = f"PUT {(path or '').rstrip('/')}/*.{ext}"
        if not w.ok:
            if not quiet:
                self.con.test(base, label, "err", w.err_class)
            return WriteResult(False, 0, url, w.err_class, token=token, body=body, bl=bl)
        if not quiet:
            self.con.test(base, label, w.status,
                          ("accepted (means nothing here — catch-all)"
                           if (bl and bl.catch_all) else "accepted")
                          if w.status in (200, 201, 204) else "")
        if w.status not in (200, 201, 204):
            return WriteResult(False, w.status, url, token=token, body=body, bl=bl)

        # a 2xx is not proof -- read it back
        targets = [url] + [t for t in (verify_at or []) if t != url]
        verified, served_at, v = False, None, None
        for t in targets:
            # no redirect-following when a normalised name is in play: a 301
            # would hide which spelling the server actually stored
            verified, v = self._verify(t, token, follow=(len(targets) == 1))
            if verified:
                served_at = t
                break
        if not quiet:
            self.con.test(base, f"  verify read-back .{ext}",
                          (v.status if (v and v.ok) else "err"),
                          "CONFIRMED" if verified else "not present — 2xx was a lie")
        if not verified:
            # A 2xx that cannot be read back means nothing was proven. Two very
            # different situations hide here, and the baseline is what tells
            # them apart:
            #
            #   catch-all path -> the 2xx is noise, exactly like the 2xx this
            #     path returns for every other name. Nothing was written, there
            #     is nothing to delete, and sending a DELETE would only produce
            #     another meaningless 2xx to misread. Drop it.
            #
            #   path with meaningful statuses -> a proxy may have lied about a
            #     write the origin discarded, or the directory may be writable
            #     but not readable. The second case puts a file on the client's
            #     server, so it is accounted for and a removal is attempted --
            #     but marked UNCONFIRMED, and it can never raise a finding.
            with self._lk:
                self.unstored += 1
            if bl is not None and bl.catch_all:
                if not quiet:
                    self.con.debug(f"  {url}: {w.status} on PUT and {bl.status} "
                                   f"on a name never written — catch-all, "
                                   f"nothing was created")
                return WriteResult(False, w.status, url, token=token, body=body, bl=bl)
            self._ledger(url, "file", confirmed=False)
            self.con.warn(f"{url}: {w.status} on PUT without a readable "
                          f"result — attempting removal anyway in case the "
                          f"directory is write-only")
            self.cleanup_one(url, token=token, confirmed=False, bl=bl)
            return WriteResult(False, w.status, url, token=token, body=body, bl=bl)

        # one file, ledgered where it actually lives
        self._ledger(served_at or url, "file")
        self.con.alert(f"file written to {dir_url(base, path)}",
                       [f"url     : {paint(url, 'b')}"]
                       + ([f"served  : {paint(served_at, 'b')}  "
                           f"(server normalised the name)"]
                          if served_at and served_at != url else [])
                       + [f"content : {body}  (date + random token)",
                          f"cleanup : this tool will DELETE it next",
                          f"if that fails: report the url so the client removes it"])
        return WriteResult(True, w.status, served_at or url, token=token, body=body, bl=bl)

    # ---- 409: the parent collection does not exist

    def try_mkcol(self, base: str, path: str, bl: Baseline = None) -> bool:
        """
        A 409 on PUT means the parent collection is missing, not that writing
        is denied. MKCOL each missing segment, then the caller retries the PUT.
        Every collection created goes in the ledger and is removed at the end
        of the target, since a directory left behind is an artefact too.
        """
        segs = [s for s in path.split("/") if s]
        if not segs:
            return False
        made = False
        for i in range(len(segs)):
            sub = "/" + "/".join(segs[:i + 1])
            r = self.http.req("MKCOL", dir_url(base, sub))
            self.con.test(base, f"MKCOL {sub}", r.status if r.ok else "err",
                          r.err_class if not r.ok else "")
            if r.ok and r.status in (200, 201):
                self._ledger(dir_url(base, sub), "collection",
                             confirmed=bool(bl and bl.distinguishes))
                made = True
            elif r.ok and r.status in (405, 301, 302):
                continue          # already exists; keep walking down
            elif r.ok and r.status in (403, 401, 501):
                break
        return made

    # ---- method override: the verb is filtered, the handler is not

    def try_override(self, base: str, path: str) -> WriteResult:
        """
        A proxy, WAF or framework that blocks the literal verb PUT frequently
        still honours a method-override header, or a lower-cased verb that a
        regex-based ACL does not match. Both are one request each and only run
        once a plain PUT has been refused.
        """
        for label, method, hdrs in (
                ("POST + X-HTTP-Method-Override", "POST", OVERRIDE_HEADERS),
                ("lowercase 'put' verb", "put", {})):
            token, body = self._poc_parts()
            fname = self._poc_name(token, "txt")
            url = join_url(base, path, fname)
            h = {"Content-Type": "text/plain"}
            h.update(hdrs)
            w = self.http.req(method, url, data=body.encode(), headers=h)
            self.con.test(base, f"{label} {path or '/'}",
                          w.status if w.ok else "err",
                          w.err_class if not w.ok else "")
            if not (w.ok and w.status in (200, 201, 204)):
                continue
            verified, _ = self._verify(url, token)
            self.con.test(base, "  verify read-back override",
                          "", "CONFIRMED" if verified else "2xx without a write")
            if not verified:
                continue
            self._ledger(url, "file")
            self.con.alert(f"file written via {label}",
                           [f"url     : {paint(url, 'b')}",
                            f"content : {body}  (date + random token)",
                            f"cleanup : this tool will DELETE it next"])
            return WriteResult(True, w.status, url, how=label, token=token, body=body)
        return WriteResult(False)

    # ---- escalation

    def escalate(self, base: str, path: str, bl: Baseline = None):
        """
        A .txt landing is High. Reaching an executable extension is Critical.
        The body stays the same inert dated string throughout -- no webshell is
        ever written, because an inert file proves the same control failure.
        """
        got, first = [], None
        for ext in EXT_MARKUP:
            res = self.try_write(base, path, ext, bl=bl)
            if res.ok:
                got.append(ext)
                # the first success is the one the report reproduces verbatim
                first = first or (res.url, res.body)
                self.cleanup_one(res.url, token=res.token, bl=bl)
        if got:
            self.add(Finding(
                title="Writable path accepts markup extensions",
                url=dir_url(base, path), method="PUT", sev=HIGH,
                evidence=f"accepted: {', '.join(got)}\nAn attacker can host "
                         f"phishing pages or stored-XSS payloads on this domain, "
                         f"inheriting its certificate and reputation.",
                confirmed=True,
                proof=f"each accepted extension was fetched back and its body "
                      f"matched /yyyy-mm-dd <token>/.",
                repro=self._repro_write(base, path, first[0], first[1], bl=bl)
                      + [f"# the same sequence succeeds for: "
                         f"{', '.join('.' + e for e in got)}"]))

        execok, xfirst = [], None
        for ext in EXT_EXEC:
            res = self.try_write(base, path, ext, bl=bl)
            if res.ok:
                execok.append(ext)
                xfirst = xfirst or (res.url, res.body)
                self.cleanup_one(res.url, token=res.token, bl=bl)
        if execok:
            self.add(Finding(
                title="Writable path accepts EXECUTABLE extensions",
                url=dir_url(base, path), method="PUT", sev=CRIT,
                evidence=f"accepted: {', '.join(execok)}\nA file with a "
                         f"server-executed extension can be written into a "
                         f"served path. Only an inert dated file was uploaded: "
                         f"the read-back returned it verbatim, which shows the "
                         f"file is stored and served but does not by itself "
                         f"show an interpreter is mapped to the extension. "
                         f"Confirm the handler mapping before reporting RCE as "
                         f"demonstrated.",
                confirmed=True,
                proof=f"each accepted extension was fetched back and its body "
                      f"matched /yyyy-mm-dd <token>/, which also means the file "
                      f"was served verbatim rather than interpreted.",
                repro=self._repro_write(base, path, xfirst[0], xfirst[1], bl=bl)
                      + [f"# the same sequence succeeds for: "
                         f"{', '.join('.' + e for e in execok)}"]))
            return

        # Executables refused -> try the classic filter evasions, then MOVE.
        # These are not separately optional: a denylist that refuses ".jsp" and
        # accepts ".jsp/" is not a control, so testing the plain spelling alone
        # would report a server as safe when it is not.
        for spell, normal, why in EXT_EVASION:
            token, _ = self._poc_parts()
            literal = self._poc_name(token, spell)
            normalised = self._poc_name(token, normal)
            res = self.try_write(
                base, path, spell, quiet=True, name=literal, bl=bl,
                verify_at=[join_url(base, path, literal),
                           join_url(base, path, normalised)])
            if not res.ok:
                continue
            self.cleanup_one(res.url, token=res.token, bl=bl)
            landed = res.url.rsplit("/", 1)[-1]
            self.add(Finding(
                title="Executable-extension filter bypassed",
                url=dir_url(base, path), method="PUT", sev=CRIT,
                evidence=f"a plain .{normal.split('.')[0]} was refused, but the "
                         f"spelling '.{spell}' was accepted and is served back "
                         f"as '{landed}'.\nmechanism: {why}\nThe filter is a "
                         f"denylist on the literal name and does not survive "
                         f"normalisation.",
                confirmed=True, proof=self._proof(res.url, res.token),
                repro=self._repro_write(
                    base, path, join_url(base, path, literal), res.body,
                    bl=bl, confirm_at=res.url)
                    + [f"# note the two names: the PUT writes '.{spell}', the "
                       f"GET that returns it is '{landed}'"]))
            return
        self.try_move(base, path, bl)

    def try_move(self, base: str, path: str, bl: Baseline = None):
        """
        Upload-time extension checks are defeated by writing an allowed name
        then renaming it. MOVE is the step people forget to block.
        """
        res = self.try_write(base, path, "txt", quiet=True, bl=bl)
        if not res.ok:
            return
        src, token = res.url, res.token
        dst = src.rsplit(".", 1)[0] + ".jsp"
        # Overwrite: F so a name collision can never destroy a client file.
        # dst is derived from our own random token, so this should not trigger.
        m = self.http.req("MOVE", src, headers={"Destination": dst,
                                                "Overwrite": "F"})
        self.con.test(base, "MOVE .txt -> .jsp", m.status if m.ok else "err",
                      m.err_class if not m.ok else "")
        if m.ok and m.status in (200, 201, 204):
            # the file now lives at dst whether or not it is served back, so it
            # goes in the ledger before anything else can return early
            self._ledger(dst, "file", confirmed=False)
            # the token, not the status: a 200 on dst from a catch-all path
            # would otherwise raise a CRITICAL for a rename that never happened
            served, v = self._verify(dst, token)
            self.con.test(base, "  verify read-back .jsp after MOVE",
                          (v.status if v.ok else "err"),
                          "CONFIRMED" if served else
                          "renamed file not served with our token")
            if served:
                self._mark_confirmed(dst)
                self.add(Finding(
                    title="Extension filter bypassed via WebDAV MOVE",
                    url=dir_url(base, path), method="MOVE", sev=CRIT,
                    evidence="a .txt was written and then renamed to .jsp, and "
                             "the renamed file is served back with this run's "
                             "token. Blocking executable extensions on PUT is "
                             "useless while MOVE is permitted.",
                    confirmed=True, proof=self._proof(dst, token),
                    repro=self._repro_write(
                        base, path, src, res.body, bl=bl, confirm_at=dst,
                        post=[f"# 1b. rename the allowed extension to an "
                              f"executable one — this is the step that is not "
                              f"blocked",
                              self._curl("MOVE", src,
                                         headers={"Destination": dst,
                                                  "Overwrite": "F"})])))
            self.cleanup_one(dst, token=token, confirmed=served, bl=bl)
        # src either was renamed away or is still there; either way reconcile
        # the ledger against the server rather than assuming
        self.cleanup_one(src, token=token, body=body, bl=bl)

    def probe_dav(self, base: str, path: str, bl: Baseline = None):
        """
        Map the wider DAV surface once a write handler is known to exist.

        PROPFIND succeeds with 207 and nothing else: RFC 4918 defines the
        success response as Multi-Status, so a plain 200 is a generic handler
        answering an unknown verb, not WebDAV. The first build accepted
        anything that was not 405/501/400, which reported 404s and redirects as
        "WebDAV methods reachable"; accepting 200 as well would report every
        catch-all host the same way. A bodyless LOCK only counts where the
        baseline shows the path's statuses mean something.
        """
        reach, authreq, noise = [], [], []
        for m in DAV_SURVEY:
            hdr = {"Depth": "1"} if m == "PROPFIND" else None
            r = self.http.req(m, dir_url(base, path), headers=hdr)
            if not r.ok:
                self.con.test(base, f"{m} {path or '/'}", "err", r.err_class)
                continue
            if m == "PROPFIND":
                good = r.status == 207
            else:
                good = r.status in (200, 423) and bl is not None \
                    and bl.distinguishes
            self.con.test(base, f"{m} {path or '/'}", r.status,
                          "" if good else
                          ("not Multi-Status — generic handler, not WebDAV"
                           if 200 <= r.status < 300 else ""))
            if good:
                reach.append(f"{m}={r.status}")
            elif r.status in (401, 407):
                authreq.append(f"{m}={r.status}")
            elif 200 <= r.status < 300:
                noise.append(f"{m}={r.status}")
        if noise and not reach:
            self.con.debug(f"  {path or '/'}: {', '.join(noise)} — 2xx without "
                           f"Multi-Status, not treated as WebDAV")
        if reach:
            self.add(Finding(
                title="WebDAV methods reachable",
                url=dir_url(base, path), method="/".join(DAV_SURVEY), sev=MED,
                evidence="answered: " + ", ".join(reach)
                         + ("\nauthentication required: " + ", ".join(authreq)
                            if authreq else "")
                         + "\nPROPFIND with Depth: 1 returning 207 also "
                           "enumerates the directory.",
                repro=self._repro(
                    "# enumerate the collection (207 Multi-Status)",
                    self._curl("PROPFIND", dir_url(base, path),
                               headers={"Depth": "1"}))))
        elif authreq:
            self.add(Finding(
                title="WebDAV methods present but authenticated",
                url=dir_url(base, path), method="/".join(DAV_SURVEY), sev=LOW,
                evidence="answered 401/407: " + ", ".join(authreq)
                         + "\nThe module is mounted; these verbs need "
                           "credentials.",
                repro=self._repro(
                    "# the verbs are mounted but need credentials",
                    self._curl("PROPFIND", dir_url(base, path),
                               headers={"Depth": "1"}))))

    # ---- cleanup

    @staticmethod
    def _reconcile(v: Resp, token: str, bl: Baseline = None):
        """
        Is our artefact still on the server? Returns (True|False|None, why).

        The rule that matters: presence is decided by OUR CONTENT, never by a
        status code. A 200 whose body does not contain this run's token is not
        our file -- it is the generic page that path serves for every name, and
        reading it as "the file is still there" is what produced a HIGH finding
        for a file that never existed.
        """
        if not v.ok:
            return None, f"verification GET failed ({v.err_class})"
        if v.status in (404, 410):
            return True, f"{v.status}"
        if 200 <= v.status < 300:
            if token:
                if poc_pattern(token).search(v.body):
                    return False, (f"{v.status} and the body still matches this "
                                   f"run's token")
                return True, (f"{v.status}, but the body does not match this "
                              f"run's token — that response is what this path "
                              f"serves for any name, not our file")
            # no token to match on (a collection): only a path whose statuses
            # mean something can support a conclusion
            if bl is not None and bl.catch_all:
                return None, (f"{v.status}, but this path returns "
                              f"{bl.status} for anything")
            return False, f"{v.status} and still served"
        if v.status in (401, 403, 407):
            return None, (f"GET now returns {v.status}, which hides whether it "
                          f"is still there")
        if 300 <= v.status < 400:
            return None, f"GET now redirects ({v.status}); cannot tell"
        return None, f"GET returns {v.status}"

    def cleanup_one(self, url: str, token="", confirmed=True, kind="file",
                    bl: Baseline = None):
        """
        Delete, then confirm against our own content.

        Three outcomes, not two: gone, still there, or unknown. A transport
        error on the check is never read as proof of removal -- that is the one
        direction you cannot afford to get wrong, since the operator has to
        disclose anything that might still be on the client's server.

        confirmed=False (the PUT returned 2xx but the file was never read back)
        downgrades everything to bookkeeping: the state goes in the ledger, and
        no finding is raised, because there is no evidence the file ever existed.
        """
        d = self.http.req("DELETE", url)
        v = self.http.req("GET", url)
        state, why = self._reconcile(v, token, bl)
        dstat = d.status if d.ok else d.err_class
        self._mark(url, state)

        if state is True:
            if confirmed:
                self.con.alert(f"{kind} removed",
                               [f"url : {url}", f"state: deleted ({why})"],
                               good=True)
            else:
                self.con.debug(f"  {url}: not present after DELETE ({why})")
            return

        if state is False:
            self.con.alert(f"COULD NOT DELETE the {kind} written",
                           [f"url   : {paint(url, 'b')}",
                            f"delete: {dstat}",
                            f"check : {why}",
                            "action: report this url so the client removes it"])
            if confirmed:
                self.add(Finding(
                    title="Cleanup failed — file left on target",
                    url=url, method="DELETE", sev=HIGH,
                    evidence=f"{url} was written, read back with this run's "
                             f"token, and could not be removed: DELETE "
                             f"returned {dstat} and {why}. Disclose it in the "
                             f"report.",
                    confirmed=True, proof=self._proof(url, token),
                    repro=self._repro(
                        f"# this file is STILL on the server. Confirm it, then "
                        f"remove it.",
                        self._curl("GET", url, show_headers=False),
                        self._curl("DELETE", url),
                        f"# re-run the GET: it must no longer return {token}",
                        self._curl("GET", url, show_headers=False))))
            return

        # unknown
        self.con.alert(f"{kind} state UNKNOWN after delete",
                       [f"url   : {paint(url, 'b')}",
                        f"delete: {dstat}",
                        f"check : {why}",
                        "action: verify by hand and disclose if present"]
                       if confirmed else
                       [f"url   : {url}",
                        f"delete: {dstat}",
                        f"check : {why}",
                        "note  : this file was never read back, so there is no "
                        "evidence it was ever created"])
        if confirmed:
            self.add(Finding(
                title="Cleanup unconfirmed — artefact may remain on target",
                url=url, method="DELETE", sev=MED,
                evidence=f"{url} was written and read back, then DELETE "
                         f"returned {dstat} and the check could not settle it: "
                         f"{why}. Verify manually.",
                repro=self._repro(
                    f"# state could not be settled automatically. Check "
                    f"whether the body still contains {token}, and remove the "
                    f"file if it does.",
                    self._curl("GET", url, show_headers=False),
                    self._curl("DELETE", url))))

    def cleanup_collections(self, bl: Baseline = None):
        """Collections created by MKCOL, removed deepest-first."""
        with self._lk:
            cols = [a["url"] for a in self.artifacts
                    if a["kind"] == "collection" and a["removed"] is None]
        for url in sorted(cols, key=lambda u: u.count("/"), reverse=True):
            self.cleanup_one(url, kind="collection", bl=bl)

    # ---- reachability

    def reach(self, url: str) -> tuple[str | None, str]:
        """
        Decide which base to test, and whether the host answers at all.

        The previous build fired one GET at "/" and dropped the whole target on
        any transport error, printing "no response (HTTPSConnectionPool(...". A
        single dropped socket, a WAF reset or an http-only port therefore lost
        every path on that host. Here: the URL's own path is tried as well as
        the root, every attempt is retried on a fresh connection, and the other
        scheme is tried when the error says the scheme is the problem.
        """
        u = urlsplit(url if "://" in url else "https://" + url)
        bases = [f"{u.scheme}://{u.netloc}"]
        if getattr(self.args, "scheme_fallback", True):
            bases.append(other_scheme(bases[0]))

        last = ""
        for i, base in enumerate(bases):
            probes = [base + "/"]
            if u.path and u.path != "/":
                probes.insert(0, join_url(base, u.path))
            for probe in probes:
                # fewer retries than a probe that matters: two schemes times two
                # probes already gives a dead-but-reachable host four chances,
                # and a list full of timing-out hosts should not cost
                # 2 x 2 x (retries+1) x --timeout each
                r = self.http.req("GET", probe, allow_redirects=True, retries=1)
                if r.ok:
                    if i:
                        self.con.warn(f"{url} — answered over "
                                      f"{urlsplit(base).scheme} instead")
                    return base, ""
                last = f"{r.err_class}: {r.error}"
                if r.err_class == "dns" or r.err_class == "aborted":
                    return None, last
                if r.err_class not in _SCHEME_FALLBACK:
                    break
        return None, last

    # ---- driver

    def candidate_paths(self, url: str) -> list[str]:
        u = urlsplit(url)
        dirs = FULL_DIRS if getattr(self.args, "all_dirs", False) \
            else CANDIDATE_DIRS
        paths = ["/" + d if d else "" for d in dirs]
        # the URL's own directory, and each ancestor: a path the server already
        # serves from is a path it has a handler for. A trailing segment that
        # looks like a file is not a directory, so it is dropped -- PUTting
        # into /app/index.php/ was a wasted request on every target.
        segs = [s for s in u.path.split("/") if s]
        if segs and "." in segs[-1]:
            segs = segs[:-1]
        for i in range(len(segs)):
            p = "/" + "/".join(segs[:i + 1])
            if p not in paths:
                paths.append(p)
        for p in self.extra_paths:
            if p not in paths:
                paths.append(p)
        return list(dict.fromkeys(paths))

    def detect(self, base: str, p: str) -> WriteResult:
        """
        Calibrate, then OPTIONS for context, then the write that decides.

        The baseline GET comes first and costs one request per path. It buys
        the only thing that makes the rest trustworthy: knowing whether this
        path's status codes mean anything before any of them is interpreted.
        """
        bl = self.baseline(base, p)
        self.probe_options(base, p)
        res = self.try_write(base, p, bl=bl)
        res.bl = bl
        if res.ok:
            return res

        if res.status == 409 and getattr(self.args, "mkcol", True):
            self.con.debug(f"  {p or '/'}: 409 — parent collection missing, "
                           f"trying MKCOL")
            if self.try_mkcol(base, p, bl):
                res = self.try_write(base, p, bl=bl)
                res.bl = bl
                if res.ok:
                    res.how = "MKCOL + PUT"
                    return res

        if res.status in (401, 403, 405) and self._override_wanted(res.status):
            ovr = self.try_override(base, p)
            ovr.bl = bl
            if ovr.ok:
                return ovr
        return res

    def _override_wanted(self, status: int) -> bool:
        if getattr(self.args, "override", False):
            return True
        # 403 means the handler is here and something said no, which is exactly
        # the case an override header defeats. 401/405 only with the flag, to
        # keep the default run at one request per path.
        return status == 403

    def run_target(self, url: str):
        self.con.banner(f"Testing {url}")
        base, why = self.reach(url)
        if base is None:
            cls = why.split(":", 1)[0] or "other"
            with self._lk:
                self.skipped.append({"url": url, "reason": why[:90],
                                     "class": cls})
            self.con.skip(f"{url} — unreachable after retries and scheme "
                          f"fallback [{cls}] {why[:60]}")
            return

        paths = self.candidate_paths(url)
        fresh = [p for p in paths if self._claim(base, p)]
        dupes = len(paths) - len(fresh)
        if not fresh:
            self.con.skip(f"{url} — all {len(paths)} path(s) already tested "
                          f"on {base}")
            return
        self.con.info(f"{len(fresh)} candidate path(s)"
                      + (f"  ({dupes} already tested on this host, skipped)"
                         if dupes else ""))

        # DETECT runs concurrently per path; EXPLOIT stays serial per path so
        # the alerts and the artefact ledger read in order.
        workers = max(1, min(getattr(self.args, "path_threads", 1) or 1,
                             len(fresh)))
        results: list[tuple[str, WriteResult]] = []
        fails = 0
        if workers > 1:
            with concurrent.futures.ThreadPoolExecutor(workers) as pool:
                for p, res in zip(fresh, pool.map(lambda q: self.detect(base, q),
                                                  fresh)):
                    results.append((p, res))
        else:
            for p in fresh:
                if _STOP.is_set():
                    break
                res = self.detect(base, p)
                results.append((p, res))
                # circuit breaker: a host that has stopped answering should not
                # burn the whole candidate list at --timeout each
                fails = fails + 1 if res.err_class else 0
                if fails >= getattr(self.args, "max_fail", 5):
                    self.con.skip(f"{url} — {fails} consecutive transport "
                                  f"failures, abandoning remaining paths")
                    break

        for p, res in results:
            if res.ok:
                self.add(Finding(
                    title=f"Server accepts arbitrary file upload via "
                          f"{'PUT' if res.how == 'PUT' else res.how}",
                    url=dir_url(base, p), method=res.how, sev=HIGH,
                    evidence=f"wrote {res.url.rsplit('/', 1)[1]} containing only "
                             f"a date and a random token, read it back and "
                             f"matched it with a regex, then "
                             f"deleted it.\nWrite permission is path-scoped: "
                             f"this directory has a write handler attached."
                             + ("" if res.how == "PUT" else
                                f"\nThe literal PUT verb was refused; the write "
                                f"succeeded through {res.how}, so the control is "
                                f"on the verb and not on the handler."),
                    confirmed=True, proof=self._proof(res.url, res.token),
                    repro=self._repro_write(
                        base, p, res.url, res.body,
                        method="POST" if res.how.startswith("POST") else
                               ("put" if "lowercase" in res.how else "PUT"),
                        headers=(OVERRIDE_HEADERS
                                 if res.how.startswith("POST") else None),
                        bl=res.bl,
                        pre=([f"# this path answered 409 until the collection "
                              f"was created, so create it first:",
                              self._curl("MKCOL", dir_url(base, p))]
                             if res.how == "MKCOL + PUT" else None))))
                self.cleanup_one(res.url, token=res.token, bl=res.bl)
                self.probe_dav(base, p, res.bl)
                if self.args.executables:
                    self.escalate(base, p, res.bl)
                else:
                    self.con.debug(f"  {p or '/'}: writable — rerun with "
                                   f"--executables to test what extensions it "
                                   f"will accept")
            elif res.status == 403:
                # handler present, denied -- worth recording, it localises config
                self.con.debug(f"  {p or '/'}: 403 — write handler present but "
                               f"denied (perms/WAF), unlike a 405")

        self.cleanup_collections(
            next((r.bl for _, r in results if r.bl is not None), None))


