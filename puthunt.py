class Console:
    """v=0 prints confirmed findings only. v=1 prints every test."""

    def __init__(self, level=0):
        self.level = level
        self._lk = threading.Lock()

    def line(self, msg):
        """One whole line, printed atomically — used by the Status heartbeat."""
        with self._lk:
            print(msg)
            sys.stdout.flush()

    def finding(self, f: "Finding"):
        with self._lk:
            tag = f" {paint('[CONFIRMED]', 'ok')}" if f.confirmed else ""
            print(f"\n{paint('['+f.sev+']', f.sev)}{tag} "
                  f"{paint(f.title, f.sev)}")
            print(f"  {paint('Target    :', 'head')} {f.url}")
            print(f"  {paint('Method    :', 'head')} {f.method}")
            print(f"  {paint('Status    :', 'head')} "
                  + (paint("CONFIRMED", "ok") if f.confirmed
                     else paint("unconfirmed (no artefact read back)", "warn")))
            if f.proof:
                for ln in f.proof.splitlines():
                    print(f"  {paint('Proof     :', 'head')} {ln}")
            for ln in (f.evidence or "").splitlines():
                print(f"  {paint('Evidence  :', 'head')} {ln}")
            if f.curl and not f.repro:
                print(f"  {paint('PoC       :', 'head')} {paint(f.curl, 'warn')}")
            if f.repro:
                print(f"  {paint('Repro     :', 'head')} "
                      + paint("copy/paste as-is — the sequence cleans up "
                              "after itself", 'dim'))
                for ln in f.repro:
                    print("    " + (paint(ln, "dim")
                                    if ln.lstrip().startswith("#")
                                    else paint(ln, "warn")))
            sys.stdout.flush()

    def alert(self, title: str, lines: list[str], good=False):
        """
        Loud, always-shown operator notice — never suppressed by verbosity.

        Reserved for the tool changing the target's state. The operator has a
        disclosure obligation for anything left behind, so this must not be
        something you can miss by running at -v 0.
        """
        key = "ok" if good else "bad"
        bar = "!" * 66
        with self._lk:
            print(f"\n{paint(bar, key)}")
            print(f"{paint('[TARGET MODIFIED]', key)} {paint(title, 'b')}")
            for ln in lines:
                print(f"  {ln}")
            print(paint(bar, key))
            sys.stdout.flush()

    def test(self, target, name, result, extra=""):
        if self.level < 1:
            return
        self.line(f"  {paint('·', 'dim')}  {paint(target, 'dim')}  "
                  f"{name:<44} {paint(f'{str(result):<5}', status_key(result))} "
                  f"{paint(extra, 'dim')}")

    def info(self, msg):
        if self.level >= 1:
            self.line(f"{paint('[info]', 'head')} {msg}")

    def debug(self, msg):
        if self.level >= 2:
            self.line(f"{paint('[dbg ]', 'dim')} {msg}")

    def warn(self, msg):
        if self.level >= 1:
            self.line(f"{paint('[warn]', 'warn')} {msg}")

    def skip(self, msg):
        """Always shown — the user needs to know a target went untested."""
        self.line(f"{paint('[skip]', 'warn')} {msg}")

    def error(self, msg):
        with self._lk:
            print(f"{paint('[err ]', 'bad')} {msg}", file=sys.stderr)
            sys.stderr.flush()

    def banner(self, msg):
        if self.level >= 1:
            self.line(f"\n{paint('=== ' + msg + ' ===', 'head')}")


